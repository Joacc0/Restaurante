    private boolean VerificaCampos() {

        //verificamos que se seleccione un producto primero 
        Producto prod = (Producto) JCBproductos.getSelectedItem();
        if (prod == null) {
            JOptionPane.showMessageDialog(null, "SELECCIONE UN PRODUCTO");
            return false;
        }

        //aca verificamos que el campo para agregar productos no este vacio
        String agregados = JTFprecioNuevo.getText().trim();
        if (agregados.isEmpty()) {
            JOptionPane.showMessageDialog(null, "INGRESE UN NUMERO DE PRODUCTOS A AGREGAR");
            return false;
        }
        try {
            int stockval = Integer.parseInt(agregados);
            if (stockval == 0) {  // Verificar que el stock sea un numero restable o sumable
                JOptionPane.showMessageDialog(null, "EL STOCK AGREGADO NO PUEDE SER 0");
                return false;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "NUMERO INVALIDO");
            return false;
        }
        
        return true;
    }
